"""Access to the character-set mapping tables kept in ``src/data_/mapping``.

The tables are generated by ``note/import_mappings.py``: Extension Set A and B
come from ``note/20542-22238.txt`` (the transcription of GB/T 20542-2006 and
GB/T 22238-2008), the legacy code spaces come from the ``tibetancodecs`` C++
arrays.  Each file uses the same schema::

    name:        table identifier, ``<source>-<target>``
    title:       human readable description
    source:      code space of the left hand side
    target:      code space of the right hand side
    sourceStart: first code of the left hand side, when the source is contiguous
    entries:     ``[from, to]`` pairs, where each side is a code or a code sequence

Codes are hexadecimal in every code space except ``hg``, whose codes are decimal
partition/bit numbers.

The Basic Set sequences are stored decomposed (NFKD), the same form the C++
arrays use, so precomposed characters never appear in the data.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Iterator, TypeAlias

import yaml

MAPPING_DIR = Path(__file__).resolve().parent.parent / "data_" / "mapping"

Sequence: TypeAlias = tuple[int, ...]
Pair: TypeAlias = tuple[Sequence, Sequence]
Table: TypeAlias = dict[str, Any]


def tableNames() -> list[str]:
    return sorted(path.stem for path in MAPPING_DIR.glob("*.yaml"))


def loadTable(name: str) -> Table:
    with (MAPPING_DIR / f"{name}.yaml").open("r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def loadTables() -> dict[str, Table]:
    return {name: loadTable(name) for name in tableNames()}


def toSequence(value: int | list[int]) -> Sequence:
    """Normalise the single-code and sequence spellings used by the YAML files."""

    return (value,) if isinstance(value, int) else tuple(value)


def iterPairs(table: Table) -> Iterator[Pair]:
    for source, target in table["entries"]:
        yield toSequence(source), toSequence(target)


def asDict(table: Table) -> dict[Sequence, Sequence]:
    """Index a table by its source sequence.

    The upstream data repeats a few source codes; the last occurrence wins, which
    is what a dictionary based lookup in the original engine effectively does.
    """

    return dict(iterPairs(table))


def codePoints(value: int | list[int]) -> str:
    """Render a code or code sequence as text, for debugging and reports."""

    return "".join(chr(code) for code in toSequence(value))
